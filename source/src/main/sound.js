const { spawn, spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const SOUND_PATH = path.join(__dirname, '..', '..', 'assets', 'notification.wav');
const SCALED_PATH = path.join(os.tmpdir(), 'activity-manager-chime.wav');
const WAV_HEADER_SIZE = 44; // PCM 16-bit mono, generated by bin/make-notification-sound.js.

// The Wayland notification daemon (mako, on Omarchy) plays no sound at all —
// it silently ignores Electron's `silent: false`. So the sound is up to us:
// we send the .wav to the first command-line player found on the machine.
// The order goes from the most likely (PipeWire) to the most generic.
const PLAYERS = [
  { bin: 'pw-play', args: (file) => [file] },
  { bin: 'paplay', args: (file) => [file] },
  { bin: 'aplay', args: (file) => ['-q', file] },
  { bin: 'ffplay', args: (file) => ['-nodisp', '-autoexit', '-loglevel', 'quiet', file] }
];

let resolved;

function resolvePlayer() {
  if (resolved !== undefined) return resolved;

  resolved =
    PLAYERS.find((player) => {
      const found = spawnSync('which', [player.bin], { stdio: 'ignore' });
      return found.status === 0;
    }) || null;

  if (!resolved) {
    console.warn('[sound] no player found (pw-play, paplay, aplay, ffplay); the alert will be silent');
  }

  return resolved;
}

// Most command-line players don't handle volume the same way (paplay uses
// 0-65536, pw-play its own flag, aplay none). Instead of depending on each
// one, we scale the .wav samples here and play the result — it works the
// same with any player. The scaled file is cached in the tmpdir and only
// rewritten when the volume changes.
let cachedVolume = null;

function scaledFileFor(volume) {
  if (cachedVolume === volume && fs.existsSync(SCALED_PATH)) return SCALED_PATH;

  const source = fs.readFileSync(SOUND_PATH);
  const header = source.subarray(0, WAV_HEADER_SIZE);
  const pcm = Buffer.from(source.subarray(WAV_HEADER_SIZE));
  const factor = Math.max(0, Math.min(100, volume)) / 100;

  for (let i = 0; i + 1 < pcm.length; i += 2) {
    const sample = pcm.readInt16LE(i);
    pcm.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(sample * factor))), i);
  }

  fs.writeFileSync(SCALED_PATH, Buffer.concat([header, pcm]));
  cachedVolume = volume;
  return SCALED_PATH;
}

/**
 * Plays the alert chime at the configured volume (0-100). It never throws or
 * blocks: an alert without sound is still an alert, and it isn't worth
 * dropping the notification over the audio.
 */
function play(volume = 100) {
  const player = resolvePlayer();
  if (!player) return;
  if (volume <= 0) return;

  let file = SOUND_PATH;
  try {
    if (volume < 100) file = scaledFileFor(volume);
  } catch (err) {
    console.warn(`[sound] couldn't adjust the volume: ${err.message}`);
  }

  try {
    const child = spawn(player.bin, player.args(file), {
      stdio: 'ignore',
      detached: true
    });
    child.on('error', (err) => console.warn(`[som] ${player.bin} falhou: ${err.message}`));
    // Without unref the player process holds Electron's event loop.
    child.unref();
  } catch (err) {
    console.warn(`[sound] couldn't play: ${err.message}`);
  }
}

module.exports = { play, SOUND_PATH };
